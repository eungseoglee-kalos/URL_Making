// 미달유형 분류는 2025-08-18에 한 번 교체됐다. 그날을 마지막으로 "계획변경"이
// 사라지고 같은 날 "영업요청 계획변경"/"생산관리 계획변경"이 시작되므로, 구
// 분류 1,951건이 둘 중 어느 쪽이었는지는 원본에 남아 있지 않다. 그래서 추측해서
// 쪼개는 대신 두 단계로 나눠 본다:
//
//   대분류 - 계획변경 계열을 하나로 묶어 2024년부터 전 기간을 비교할 수 있게 한다.
//   세부분류 - 신 분류가 기록된 구간에서만 영업요청/생산관리를 구분해 보여준다.
//
// 목록에 없는 값은 버리거나 "기타"로 삼키지 않고 그대로 통과시킨다. 새 유형이
// 생기면 조용히 묻히는 대신 화면에 드러나야 하기 때문이다.

export const UNCLASSIFIED = "(미분류)";

/** 신 분류 기준으로 정규화한 이름. 구분이 불가능한 건은 별도 라벨로 남긴다. */
const DETAIL_MAP: Record<string, string> = {
  // 고객사 납기변경은 의미상 영업요청 계획변경과 같아 합친다.
  "고객사 납기변경": "영업요청 계획변경",
  // 신 분류의 어느 쪽인지 알 수 없는 구 분류. 이름으로 그 사실을 드러낸다.
  계획변경: "계획변경(구분 전)",
};

/** 전 기간 비교용 대분류. */
const GROUP_MAP: Record<string, string> = {
  계획변경: "계획변경",
  "영업요청 계획변경": "계획변경",
  "생산관리 계획변경": "계획변경",
  "고객사 납기변경": "계획변경",
};

export type FailTypeMode = "group" | "detail";

export function toFailType(raw: string | null, mode: FailTypeMode): string {
  if (!raw) return UNCLASSIFIED;
  const map = mode === "group" ? GROUP_MAP : DETAIL_MAP;
  return map[raw] ?? raw;
}

